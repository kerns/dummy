<?php

// Render the PHP demo and its selected assets into a self-contained static site.
if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
$destination = $argv[1] ?? $root . '/build/demo';
$staging = sys_get_temp_dir() . '/dummy-demo-' . bin2hex(random_bytes(8));
$exitCode = 0;
$remove = static function (string $path) use (&$remove): void {
    if (is_dir($path) && !is_link($path)) {
        foreach (new FilesystemIterator($path) as $entry) {
            $remove($entry->getPathname());
        }
        rmdir($path);
    } else {
        unlink($path);
    }
};
$copy = static function (string $source, string $target) use (&$copy): void {
    if (is_dir($source)) {
        if (!is_dir($target)) {
            mkdir($target, 0775, true);
        }
        foreach (new FilesystemIterator($source) as $entry) {
            $copy($entry->getPathname(), $target . '/' . $entry->getFilename());
        }
    } elseif (!copy($source, $target)) {
        throw new RuntimeException("Could not copy $source.");
    }
};

try {
    if (!is_dir(dirname($destination))) {
        mkdir(dirname($destination), 0775, true);
    }
    $destination = realpath(dirname($destination)) . '/' . basename($destination);
    if (is_link($destination) || $destination === $root || str_starts_with($root . '/', $destination . '/')) {
        throw new RuntimeException('The output directory cannot be the source directory or one of its parents.');
    }
    if (file_exists($destination) && (!is_dir($destination) || (!is_file($destination . '/.dummy-static-demo')
        && count(scandir($destination)) > 2))) {
        throw new RuntimeException('The output directory must be empty or a previous Dummy demo export.');
    }
    mkdir($staging . '/dummy/cache', 0775, true);
    $GLOBALS['dummy_path'] = 'dummy';
    $GLOBALS['dummy_assets_path'] = $root . '/dummy/assets';
    $GLOBALS['dummy_cache_path'] = $staging . '/dummy/cache';
    $GLOBALS['dummy_static_demo'] = true;
    ob_start();
    try {
        require $root . '/demo.php';
        $html = ob_get_contents();
    } finally {
        ob_end_clean();
    }
    if (str_contains($html, '<em>Dummy:') || str_contains($html, '<?')) {
        throw new RuntimeException('The demo did not render cleanly.');
    }
    $copy($root . '/demo_files', $staging . '/demo_files');
    $copy($root . '/CREDITS.md', $staging . '/CREDITS.md');
    $copy($root . '/LICENSE', $staging . '/LICENSE');

    $document = new DOMDocument();
    $previousErrors = libxml_use_internal_errors(true);
    $document->loadHTML($html);
    libxml_clear_errors();
    libxml_use_internal_errors($previousErrors);
    foreach ((new DOMXPath($document))->query('//*[@src or @href]') as $node) {
        foreach (['src', 'href'] as $attribute) {
            $url = $node->getAttribute($attribute);
            if (str_starts_with($url, 'dummy/assets/')) {
                $relative = rawurldecode(substr($url, strlen('dummy/assets/')));
                $source = \Kerns\Dummy\Runtime::resolve($root . '/dummy/assets', $relative);
                if ($source === null || !is_file($source)) {
                    throw new RuntimeException("Missing demo asset: $url.");
                }
                $target = $staging . '/dummy/assets/' . $relative;
                if (!is_dir(dirname($target))) {
                    mkdir(dirname($target), 0775, true);
                }
                $copy($source, $target);
            }
            if (preg_match('~^(dummy/|demo_files/)~', $url) && !is_file($staging . '/' . rawurldecode($url))) {
                throw new RuntimeException("Missing exported resource: $url.");
            }
        }
    }
    file_put_contents($staging . '/index.html', $html);
    file_put_contents($staging . '/.nojekyll', '');
    file_put_contents($staging . '/.dummy-static-demo', "Generated by tools/build-demo.php\n");
    if (is_dir($destination)) {
        $remove($destination);
    }
    $copy($staging, $destination);
    echo "Static demo built in $destination\n";
} catch (Throwable $error) {
    fwrite(STDERR, $error->getMessage() . "\n");
    $exitCode = 1;
} finally {
    if (is_dir($staging)) {
        $remove($staging);
    }
}
exit($exitCode);
